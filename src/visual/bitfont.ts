export const GLYPH_W = 5;
export const GLYPH_H = 8;
/** Avanço padrão: 5 de glifo + 1 de espaço entre letras. */
export const ADVANCE = GLYPH_W + 1;
/** Altura de linha com folga para o acento das maiúsculas. */
export const LINE_H = 10;

/** O acento de uma minúscula cabe nas linhas 0–1; o de uma maiúscula sobe. */
function markTop(base: string, mark: string[]): number {
  const isUpper = base >= 'A' && base <= 'Z';
  return isUpper ? -mark.length : 2 - mark.length;
}

function glyphOf(ch: string): string[] | null {
  return G[ch] ?? null;
}

/** Largura de um texto em pixels do canvas interno. */
export function measure(text: string, spacing = 1): number {
  if (text.length === 0) return 0;
  return text.length * (GLYPH_W + spacing) - spacing;
}

export interface TextOptions {
  /** Pixels entre letras. Padrão 1. */
  spacing?: number;
  /** 'left' | 'center' | 'right' — em relação a x. */
  align?: 'left' | 'center' | 'right';
}

/**
 * Desenha uma linha de texto. `x`/`y` são arredondados: o texto vive no grid.
 * Retorna a largura desenhada.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  opts: TextOptions = {},
): number {
  const { spacing = 1, align = 'left' } = opts;
  const w = measure(text, spacing);
  let px = Math.round(x);
  if (align === 'center') px = Math.round(x - w / 2);
  else if (align === 'right') px = Math.round(x - w);
  const py = Math.round(y);

  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const gx = px + i * (GLYPH_W + spacing);
    const composed = COMPOSED[ch];
    const baseChar = composed ? composed[0] : ch;
    const rows = glyphOf(baseChar);
    if (rows) blit(ctx, rows, gx, py);
    if (composed) {
      const [, above, below] = composed;
      if (above) blit(ctx, MARK[above], gx, py + markTop(baseChar, MARK[above]));
      if (below) blit(ctx, BELOW[below], gx, py + GLYPH_H - 1);
    }
  }
  return w;
}

function blit(ctx: CanvasRenderingContext2D, rows: string[], x: number, y: number): void {
  for (let r = 0; r < rows.length; r++) {
    const line = rows[r];
    let c = 0;
    while (c < line.length) {
      if (line[c] !== '#') {
        c++;
        continue;
      }
      let run = 1;
      while (c + run < line.length && line[c + run] === '#') run++;
      ctx.fillRect(x + c, y + r, run, 1);
      c += run;
    }
  }
}

/** Quebra o texto em linhas que cabem em `maxWidth` pixels. */
export function wrap(text: string, maxWidth: number, spacing = 1): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (measure(next, spacing) <= maxWidth || !line) {
      line = next;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}
